#!/usr/bin/env python3
"""Writes syntaxes/asili.sublime-syntax, the highlighter Zola uses for ```asili code blocks.

The keyword and type lists come from the playground's generated block in its main.js (the same
lists the editor highlights with, and that CI checks against Asili's compiler). So the site and
the editor cannot disagree about what is a keyword.

Usage:
  python3 scripts/build_syntax.py --playground DIR          # write the file
  python3 scripts/build_syntax.py --playground DIR --check  # fail if the file is out of date
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "syntaxes" / "asili.sublime-syntax"


def word_lists(playground: pathlib.Path) -> tuple[list[str], list[str]]:
    js = (playground / "main.js").read_text(encoding="utf-8")
    block = js[js.index("// <generated"): js.index("// </generated>")]
    keywords = re.search(r"const KEYWORDS = new Set\(\[(.*?)\]\);", block, re.S)
    types = re.search(r"const BUILTIN_TYPES = new Set\(\[(.*?)\]\);", block, re.S)
    if not keywords or not types:
        raise SystemExit("error: could not find KEYWORDS and BUILTIN_TYPES in the playground's main.js")
    words = lambda s: re.findall(r'"([^"]+)"', s)
    return words(keywords.group(1)), words(types.group(1))


def alternation(words: list[str]) -> str:
    # Longest first, so `au_biti` is not matched as `au`.
    return "|".join(sorted(words, key=len, reverse=True))


def render(keywords: list[str], types: list[str]) -> str:
    return f"""%YAML 1.2
---
# Generated by scripts/build_syntax.py from the playground's main.js. Do not edit by hand.
name: Asili
file_extensions: [as]
scope: source.asili
contexts:
  main:
    - match: '#.*$'
      scope: comment.line.number-sign.asili
    - match: '"'
      scope: punctuation.definition.string.begin.asili
      push: string
    - match: '\\b\\d+(\\.\\d+)?\\b'
      scope: constant.numeric.asili
    - match: '\\b(?:{alternation(keywords)})\\b'
      scope: keyword.control.asili
    - match: '\\b(?:{alternation(types)})\\b'
      scope: storage.type.asili
    - match: '\\b[A-Z][A-Za-z0-9_]*\\b'
      scope: entity.name.type.asili
    - match: '\\b[a-z_][A-Za-z0-9_]*(?=\\s*\\()'
      scope: entity.name.function.asili
  string:
    - meta_scope: string.quoted.double.asili
    - match: '\\\\.'
      scope: constant.character.escape.asili
    - match: '"'
      scope: punctuation.definition.string.end.asili
      pop: true
"""


def main(argv: list[str]) -> int:
    if "--playground" not in argv:
        print(__doc__)
        return 2
    playground = pathlib.Path(argv[argv.index("--playground") + 1])
    keywords, types = word_lists(playground)
    text = render(keywords, types)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"error: {OUT.relative_to(ROOT)} is out of date: run scripts/build_syntax.py --playground {playground}")
            return 1
        print("ok: syntax matches the playground's word lists")
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(keywords)} keywords, {len(types)} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
